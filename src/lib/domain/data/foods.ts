const BY_KEY: ReadonlyMap<FoodKey, Food> = new Map(RAW_FOODS.map((f) => [f.key, f]));

export const FOODS: readonly Food[] = RAW_FOODS;

/** Safe lookup — returns undefined rather than throwing, per the `noUncheckedIndexedAccess` contract. */
export function getFood(key: FoodKey): Food | undefined {
  return BY_KEY.get(key);
}

/** Total lookup: throws a loud error in dev if a key is missing from the DB. */
export function requireFood(key: FoodKey): Food {
  const food = BY_KEY.get(key);
  if (!food) {
    throw new Error(`[foods] unknown FoodKey: ${key}. Add it to RAW_FOODS.`);
  }
  return food;
}

export function hasFood(key: FoodKey): boolean {
  return BY_KEY.has(key);
}

export function foodsInCategory(category: Food['category']): readonly Food[] {
  return RAW_FOODS.filter((f) => f.category === category);
}

export function searchFoods(query: string, limit = 20): readonly Food[] {
  const q = query.trim().toLowerCase();
  if (!q) return RAW_FOODS.slice(0, limit);
  const scored = RAW_FOODS.map((food) => {
    const haystack = [food.name, food.category, ...food.localNames].join(' ').toLowerCase();
    const idx = haystack.indexOf(q);
    if (food.key === q) return { food, score: 0 };
    // -1 means "no match". Note that index 0 is a *match*, so this cannot use a
    // truthiness check — that would drop every prefix match and keep nothing.
    if (idx === -1) return { food, score: 999 };
    return {
      food,
      score: 1 + idx / 100 + (food.localNames.some((n) => n.toLowerCase().startsWith(q)) ? -0.5 : 0),
    };
  });
  return scored
    .filter((s) => s.score < 999)
    .sort((a, b) => a.score - b.score)
    .slice(0, limit)
    .map((s) => s.food);
}

/** Total nutrition for `grams` of a food, rounded to sensible precision. */
export function nutritionForGrams(key: FoodKey, grams: number): NutritionTotals {
  const food = requireFood(key);
  const factor = grams / 100;
  const n = food.nutrition;
  return {
    calories: Math.round(n.calories * factor),
    protein: round1(n.protein * factor),
    carbs: round1(n.carbs * factor),
    fat: round1(n.fat * factor),
    fiber: round1(n.fiber * factor),
  };
}

export function round1(n: number): number {
  return Math.round(n * 10) / 10;
}

export function sumNutrition(items: readonly NutritionTotals[]): NutritionTotals {
  return items.reduce<NutritionTotals>(
    (acc, i) => ({
      calories: acc.calories + i.calories,
      protein: round1(acc.protein + i.protein),
      carbs: round1(acc.carbs + i.carbs),
      fat: round1(acc.fat + i.fat),
      fiber: round1(acc.fiber + i.fiber),
    }),
    { calories: 0, protein: 0, carbs: 0, fat: 0, fiber: 0 },
  );
}

/** Cheap protein-per-rupee ranking — the backbone of the budget optimizer. */
export function proteinPerRupee(key: FoodKey, grams = 100): number {
  const nutrition = nutritionForGrams(key, grams);
  const price = requireFood(key).price;
  const cost = (grams / price.unitGrams) * price.typicalPrice;
  if (cost <= 0) return 0;
  return round1(nutrition.protein / cost);
}

export function caloriesPerRupee(key: FoodKey, grams = 100): number {
  const nutrition = nutritionForGrams(key, grams);
  const price = requireFood(key).price;
  const cost = (grams / price.unitGrams) * price.typicalPrice;
  if (cost <= 0) return 0;
  return round1(nutrition.calories / cost);
}
