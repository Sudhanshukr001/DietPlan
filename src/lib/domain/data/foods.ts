const g = (grams: number, unit: Portion['unit'] = 'g'): Portion => ({
  grams,
  gramsLow: Math.round(grams * 0.85),
  gramsHigh: Math.round(grams * 1.15),
  label: `${grams} g`,
  unit,
});

const piece = (grams: number, label: string): Portion => ({
  grams,
  gramsLow: Math.round(grams * 0.85),
  gramsHigh: Math.round(grams * 1.15),
  label,
  unit: 'piece',
});

const ml = (volume: number, label: string): Portion => ({
  grams: volume,
  gramsLow: Math.round(volume * 0.9),
  gramsHigh: Math.round(volume * 1.1),
  label,
  unit: 'ml',
});

const cup = (grams: number, label: string): Portion => ({
  grams,
  gramsLow: Math.round(grams * 0.9),
  gramsHigh: Math.round(grams * 1.1),
  label,
  unit: 'cup',
});

